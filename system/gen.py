# Generates src/styles/base.css from system/tranter.json and the starter's reset (system/reset.css).
# Run: python3 -I system/gen.py   (never edit base.css by hand)
import json, os
HERE = os.path.dirname(os.path.abspath(__file__))
S = json.load(open(os.path.join(HERE, 'tranter.json')))
V = S['viewport']; R = V['reference']; DMIN = V['desktopMin']
def num(x):
    s = ('%.3f' % x).rstrip('0').rstrip('.')
    return s
def formula(n):
    return (f"clamp(var(--{n}-min) / 16 * 1rem, ((var(--{n}-min) - ((var(--{n}-max) - var(--{n}-min)) / (var(--viewport-max) - var(--viewport-min)) * var(--viewport-min))) / 16 * 1rem + ((var(--{n}-max) - var(--{n}-min)) / (var(--viewport-max) - var(--viewport-min))) * 100vw), var(--{n}-max) / 16 * 1rem)")
out = []
w = out.append
w("/* Design tokens: GENERATED by system/gen.py from system/tranter.json. Do not edit by hand. */")
w("/* Season Collection VF TRIAL: development only (Sam, Nov 9). The licence is bought before the site goes live. */")
w('@font-face {\n  font-family: "Season";\n  src: url("/fonts/SeasonCollectionVF-TRIAL.ttf") format("truetype");\n  font-weight: 300 900;\n  font-style: oblique 0deg 11deg;\n  font-display: block;\n}')
w(":root {")
w("  /* Swatches (Figma) */")
for k, v in [('ink', '#2c0f0a'), ('cream', '#e1dcbc'), ('sand', '#ded5c2'), ('stone', '#e8e7e2'), ('mist', '#c2d3d7'), ('khaki', '#cac3a5')]:
    w(f"  --{k}: {v};")
w("  /* Tones: the Figma's opacities of the text colour */")
w("  --tone-strong: 100%;\n  --tone-pill: 80%;\n  --tone-border: 60%;\n  --tone-muted: 50%;\n  --tone-faint: 30%;")
w("\n  /* Typography primitives */")
w(f"  --season: {S['fonts']['season']};")
w("  --primary-family: var(--season);\n  --mono-family: ui-monospace, \"SF Mono\", SFMono-Regular, Menlo, Consolas, monospace;")
w("  --sans: \"SERF\" 0;\n  --mix: \"SERF\" 50;\n  --serif: \"SERF\" 100;")
w("\n  /* Borders & focus */\n  --border-width: 0.0625rem;\n  --focus-width: 0.125rem;\n  --focus-offset: 0.1827rem;\n  --focus-offset-inner: calc(var(--focus-width) * -1);")
w("\n  /* Hover motion (no other motion before Sam's brief) */\n  --hover-duration: 400ms;\n  --arrow-duration: 600ms;\n  --hover-ease: var(--ease-smooth);\n  --open-duration: 240ms;\n  --open-ease: var(--ease-smooth);\n  --loader-duration: 600ms;\n  --loader-ease: var(--ease-osmo);\n  --page-leave-duration: 320ms;\n  --page-leave-ease: var(--ease-smooth);\n  --page-arrive-duration: 560ms;\n  --page-arrive-ease: var(--ease-osmo);\n  --ease-smooth: cubic-bezier(0.16, 1, 0.3, 1);\n  --ease-osmo: cubic-bezier(0.625, 0.05, 0, 1);\n  --ease-rebound: cubic-bezier(0.34, 1.56, 0.64, 1);")
w("\n  /* Radius */\n  --radius-small: 0.625rem;\n  --radius-main: 0.875rem;\n  --radius-round: 100vw;")
w(f"\n  /* Fluid scale range: phone {V['phone']} to tablet {V['tabletMax']}; the computer range is in the 64rem block */")
w(f"  --viewport-min: {V['phone']};\n  --viewport-max: {V['tabletMax']};")
w("\n  /* Max width: the content width at the reference width; nothing grows beyond it */")
w("  --max-width-small: 70rem;\n  --max-width-main: calc((var(--viewport-max) - 2 * var(--site-margin-max)) / 16 * 1rem);\n  --max-width-full: 100%;")
w("\n  /* Nav */\n  --nav-height: 3.5rem;")
w("\n  /* Fluid tokens: phone and tablet values here, the computer's in the 64rem block */")
for n, (ph, tb, dk) in S['fluid'].items():
    w(f"  --{n}: {formula(n)};")
    w(f"  --{n}-min: {num(ph)};\n  --{n}-max: {num(tb)};")
w("\n  /* Role tokens: one job each, pointing at a step of the scale (change the step, every use follows) */")
for n, r in S.get('roles', {}).items():
    w(f"  --{n}: var(--{r['ref']});")
w("\n  /* Floors: reading text stops shrinking here (applied with max() in the text-style rules) */")
for n, f in S['floors'].items():
    w(f"  --{n}-floor: {num(f / 16)}rem;")
w("\n  /* Text style properties */")
for n, t in S['text'].items():
    w(f"  --{n}-line-height: {t['lh']};\n  --{n}-letter-spacing: {t['ls']};\n  --{n}-text-transform: {t['tt']};\n  --{n}-font-family: var(--season);\n  --{n}-font-weight: {t['weight']};\n  --{n}-font-variation: \"SERF\" {t['axis']};\n  --{n}-font-feature: {t['ff']};\n  --{n}-margin-top: 0rem;\n  --{n}-margin-bottom: 0rem;\n  --{n}-text-wrap: {'nowrap' if n in ('text-action','text-label','text-index','text-index-caps','text-date') else 'pretty'};")
w("\n  /* Site layout */\n  --site-width: calc(100% - var(--site-margin) * 2);\n  /* The layout grid's columns: phone here, tablet and computer in the media blocks */\n  --site-columns: 4;")
w("}")
phone_roles = {n: r['phone'] for n, r in S.get('roles', {}).items() if r.get('phone')}
if phone_roles:
    w("/* Phone: role tokens that point at another step below the tablet */\n@media (width < 48rem) {\n  :root {")
    for n, ref in phone_roles.items():
        w(f"    --{n}: var(--{ref});")
    w("  }\n}")
w("/* Tablet: 8 columns (Lumos Grid breakpoint 48rem) */\n@media (width >= 48rem) {\n  :root {\n    --site-columns: 8;\n  }\n}")
w(f"/* Computer, 1024 to {R}: everything scales with the grid. Each -min is -max x {DMIN} / {R}. */")
w("@media (width >= 64rem) {\n  :root {\n    --site-columns: 12;")
w(f"    --viewport-min: {DMIN};\n    --viewport-max: {R};")
for n, (ph, tb, dk) in S['fluid'].items():
    w(f"    --{n}-min: {num(dk * DMIN / R)};\n    --{n}-max: {num(dk)};")
w("  }\n}")
# themes
w("""/* Color themes: sand (default), stone, mist, dark (ink with cream text), dark-sand (ink with sand text) */
:root,
.theme-light,
.theme-stone,
.theme-mist,
.theme-dark .theme-invert {
  color-scheme: light;
  --background: var(--sand);
  --text: var(--ink);
  --text-2: color-mix(in srgb, var(--text) var(--tone-muted), transparent);
  --text-3: color-mix(in srgb, var(--text) var(--tone-faint), transparent);
  --border: color-mix(in srgb, var(--text) var(--tone-border), transparent);
  --background-2: var(--stone);
  --background-3: var(--mist);
  --background-skeleton: color-mix(in srgb, currentcolor 8%, transparent);
  --heading-accent: var(--text);
  --focus: var(--text);
  --selection-background: color-mix(in srgb, var(--text) 16%, transparent);
  --selection-text: var(--text);
  --marker-color: var(--text);
  --pill-text: color-mix(in srgb, var(--text) var(--tone-pill), transparent);
  --pill-border: color-mix(in srgb, var(--text) calc(var(--tone-pill) * var(--tone-border) / 100%), transparent);
  --pill-border-solid: var(--pill-text);
  --button-background: transparent;
  --button-border: var(--pill-border);
  --button-text: var(--pill-text);
  --button-background-hover: transparent;
  --button-border-hover: var(--text);
  --button-text-hover: var(--text);
  --button-2-background: transparent;
  --button-2-border: var(--pill-border-solid);
  --button-2-text: var(--pill-text);
  --button-2-background-hover: transparent;
  --button-2-border-hover: var(--text);
  --button-2-text-hover: var(--text);
  --link-text: var(--text-2);
  --link-border: transparent;
  --link-text-hover: var(--text);
  --link-border-hover: transparent;
}
.theme-stone {
  --background: var(--stone);
}
.theme-mist {
  --background: var(--mist);
}
.theme-dark,
.theme-dark-sand,
.theme-light .theme-invert {
  color-scheme: dark;
  --background: var(--ink);
  --text: var(--cream);
  --text-2: color-mix(in srgb, var(--text) var(--tone-muted), transparent);
  --text-3: color-mix(in srgb, var(--text) var(--tone-faint), transparent);
  --border: color-mix(in srgb, var(--text) var(--tone-border), transparent);
  --background-skeleton: color-mix(in srgb, currentcolor 10%, transparent);
  --heading-accent: var(--text);
  --focus: var(--text);
  --selection-background: color-mix(in srgb, var(--text) 24%, transparent);
  --selection-text: var(--text);
  --marker-color: var(--khaki);
  --pill-text: color-mix(in srgb, var(--text) var(--tone-pill), transparent);
  --pill-border: color-mix(in srgb, var(--text) calc(var(--tone-pill) * var(--tone-border) / 100%), transparent);
  --pill-border-solid: var(--pill-text);
  --button-border: var(--pill-border);
  --button-text: var(--pill-text);
  --button-border-hover: var(--text);
  --button-text-hover: var(--text);
  --button-2-border: var(--pill-border-solid);
  --button-2-text: var(--pill-text);
  --link-text: var(--text-2);
  --link-text-hover: var(--text);
}
.theme-dark-sand {
  --background: var(--ink);
  --text: var(--sand);
  --marker-color: var(--sand);
}
:root,
[class*="theme-"] {
  background-color: var(--background);
  color: var(--text);
}""")
w(open(os.path.join(HERE, 'reset.css')).read().rstrip())
# text styles
w("/* Text styles: GENERATED. A text style lives only here (Sam, Nov 9). */")
tag = {'text-main': 'body,\n', 'h1': 'h1,\n', 'h2': 'h2,\n', 'h3': 'h3,\nh4,\nh5,\nh6,\n'}
for n, t in S['text'].items():
    cls = '.text-style-' + n.replace('text-', '') if n.startswith('text-') else '.text-style-' + n
    size = f"var(--{n})" if n not in S['floors'] else f"max(var(--{n}-floor), var(--{n}))"
    w(f"{tag.get(n, '')}{cls} {{\n  font-family: var(--{n}-font-family);\n  font-size: {size};\n  font-weight: var(--{n}-font-weight);\n  font-variation-settings: var(--{n}-font-variation);\n  font-feature-settings: var(--{n}-font-feature);\n  line-height: var(--{n}-line-height);\n  letter-spacing: var(--{n}-letter-spacing);\n  text-transform: var(--{n}-text-transform);\n  text-wrap: var(--{n}-text-wrap);\n  --_margin-top: var(--{n}-margin-top);\n  --_margin-bottom: var(--{n}-margin-bottom);")
    if 'em' in t:
        ax, wt = t['em']
        w(f"  & em {{\n    font-style: normal;\n    font-weight: {wt};\n    font-variation-settings: \"SERF\" {ax};\n  }}")
    w("}")
w("""/* Text trim: a text box runs from the cap top of its first line to the baseline of its last */
h1,
h2,
h3,
h4,
h5,
h6,
p,
[class*="text-style-"] {
  text-box: trim-both cap alphabetic;
}""")
open(os.path.join(HERE, '..', 'src', 'styles', 'base.css'), 'w').write('\n'.join(out) + '\n')
print('base.css written,', sum(1 for _ in open(os.path.join(HERE, '..', 'src', 'styles', 'base.css'))), 'lines')
